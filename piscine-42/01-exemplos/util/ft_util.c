#include <unistd.h>
#include "ft_util.h"

void	ft_putchar(char c)
{
	write(1, &c, 1);
}

void	ft_putstr(char *str)
{
	while (*str != '\0')
	{
		write(1, str, 1);
		str++;
	}
}

void	ft_putendl(char *str)
{
	ft_putstr(str);
	write(1, "\n", 1);
}

void	ft_putnbr(int nb)
{
	long	n;

	n = nb;
	if (n < 0)
	{
		ft_putchar('-');
		n = -n;
	}
	if (n >= 10)
		ft_putnbr(n / 10);
	ft_putchar(n % 10 + '0');
}

void	ft_putptr(void *ptr)
{
	unsigned long	n;
	char			buf[12];
	int				i;

	n = (unsigned long)ptr;
	i = 12;
	while (i > 0)
	{
		i--;
		buf[i] = "0123456789abcdef"[n % 16];
		n = n / 16;
	}
	write(1, "0x", 2);
	write(1, buf, 12);
}
